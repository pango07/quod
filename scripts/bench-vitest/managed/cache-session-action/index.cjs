'use strict'
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const action = path.resolve(process.env.INPUT_ACTION || '')
const session = path.resolve(process.env.INPUT_SESSION || '')
const artifacts = path.resolve(process.env.INPUT_ARTIFACTS || '')
const temporary = fs.realpathSync(process.env.RUNNER_TEMP)
const parent = fs.realpathSync(path.dirname(session))
assert(parent === temporary || parent.startsWith(temporary + path.sep), 'private session must be job-local')
assert(session !== artifacts && !session.startsWith(artifacts + path.sep), 'private session cannot be an evidence artifact')
assert(typeof process.env.ACTIONS_RUNTIME_TOKEN === 'string' && process.env.ACTIONS_RUNTIME_TOKEN, 'JavaScript Actions cache session required')
const {captureCacheAuth} = require(path.join(action, 'src/managed-auth.js'))
captureCacheAuth(session)
const stat = fs.lstatSync(session)
assert(stat.isFile() && !stat.isSymbolicLink() && (stat.mode & 0o777) === 0o600, 'private cache session mode required')
console.log('Private job-local matrix cache session captured.')
