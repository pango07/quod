//! `stillpass bench`: the two spike numbers, overhead (A8) and hit rate
//! (A11), written to report.md. Every number comes from the run events the
//! child `stillpass run` processes write, never from parsing their output.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, bail};
use clap::Args;
use serde_json::Value;

use crate::state::State;

#[derive(Args)]
pub struct BenchArgs {
    /// The spike repo checkout. Never modified: the bench works on clones.
    #[arg(long)]
    repo: PathBuf,
    /// Commits for the hit-rate run (A11), oldest first ending at HEAD.
    #[arg(long, default_value_t = 50)]
    commits: usize,
    /// Step B, the memoized step.
    #[arg(long, default_value = "go test ./...")]
    step: String,
    /// Step A, run with network before step B on every commit.
    #[arg(long, default_value = "go mod download")]
    setup: String,
    /// Runs per overhead series; the first of each is dropped as warm-up.
    #[arg(long, default_value_t = 10)]
    runs: usize,
    /// Skip the overhead series (A8).
    #[arg(long)]
    no_overhead: bool,
    /// Skip the hit-rate series (A11).
    #[arg(long)]
    no_hit_rate: bool,
    /// Also measure miss latency on a one-file change, cold vs --warm.
    #[arg(long)]
    one_file: bool,
    /// The file the one-file series appends a comment to before each pair.
    #[arg(long, default_value = "api/client.go")]
    touch: String,
    /// Alternate the overhead series run by run (plain, observed, plain, ...)
    /// so load from elsewhere on the box hits every series alike.
    #[arg(long)]
    interleave: bool,
    /// An extra observed series with NAME=VALUE[,NAME=VALUE...] in the
    /// child's environment (repeatable), to attribute overhead to a mechanism.
    #[arg(long = "extra-series", value_name = "NAME=VALUE[,...]")]
    extra_series: Vec<String>,
    #[arg(long)]
    vm: bool,
    #[arg(long, default_value = "report.md")]
    out: PathBuf,
}

struct Sample {
    wall: Duration,
    event: Value,
}

/// An overhead series: its label and, for an observed series, the extra
/// environment of the child `stillpass run` (`None` is the plain baseline).
type Series = (String, Option<Vec<(String, String)>>);

pub fn bench(state: &State, args: BenchArgs) -> anyhow::Result<u8> {
    if args.vm {
        bail!("--vm needs the 0b Firecracker backend (T13-T16), which is not built");
    }
    let repo = args.repo.canonicalize()?;
    let work = state.dir.join("bench");
    sp_cas::remove_any(&work)?;
    std::fs::create_dir_all(&work)?;
    let exe = std::env::current_exe()?;
    let head = git(&repo, &["rev-parse", "HEAD"])?;

    let mut report = String::new();
    writeln!(report, "# Stillpass spike benchmark\n")?;
    writeln!(
        report,
        "Spike repo `{}` at `{}`. Step A `{}`, step B `{}`. Generated by `stillpass bench`.\n",
        origin(&repo),
        &head[..12],
        args.setup,
        args.step
    )?;
    report += &machine_table(&state.dir)?;

    let mut totals = Vec::new();
    if !args.no_overhead {
        let (table, line) = overhead(&exe, &repo, &work, &args)?;
        report += &table;
        totals.push(line);
    }
    if !args.no_hit_rate {
        let (table, line) = hit_rate(&exe, &repo, &work, &args)?;
        report += &table;
        totals.push(line);
    }
    if args.one_file {
        let (table, line) = one_file(&exe, &repo, &work, &args)?;
        report += &table;
        totals.push(line);
    }
    writeln!(report, "## Totals\n")?;
    for t in &totals {
        writeln!(report, "- {t}")?;
    }
    std::fs::write(&args.out, &report).with_context(|| format!("write {}", args.out.display()))?;
    eprintln!("wrote {}", args.out.display());
    for t in totals {
        eprintln!("{t}");
    }
    sp_cas::remove_any(&work)?;
    Ok(0)
}

/// A8: plain go test vs the full observed path, both cold.
fn overhead(
    exe: &Path,
    repo: &Path,
    work: &Path,
    args: &BenchArgs,
) -> anyhow::Result<(String, String)> {
    let tree = work.join("overhead-tree");
    clone_at(repo, &tree, "HEAD")?;
    copy_module_cache(repo, &tree)?;
    run_setup(exe, &work.join("setup-state"), &tree, &args.setup)?;

    // Series 0 is plain, 1 the observed path, then one observed series per
    // --extra-series with that variable set in the child's environment.
    let mut series: Vec<Series> = vec![
        ("Plain (same sandbox, no FUSE or overlay)".into(), None),
        (
            "Observed (import, serve, overlay, sandbox, record)".into(),
            Some(Vec::new()),
        ),
    ];
    for e in &args.extra_series {
        let env = e
            .split(',')
            .map(|kv| match kv.split_once('=') {
                Some((k, v)) => Ok((k.to_string(), v.to_string())),
                None => bail!("--extra-series {e:?}: {kv:?} is not NAME=VALUE"),
            })
            .collect::<anyhow::Result<Vec<_>>>()?;
        series.push((format!("Observed, {e}"), Some(env)));
    }
    let order: Vec<(usize, usize)> = if args.interleave {
        (0..args.runs)
            .flat_map(|i| (0..series.len()).map(move |s| (s, i)))
            .collect()
    } else {
        (0..series.len())
            .flat_map(|s| (0..args.runs).map(move |i| (s, i)))
            .collect()
    };
    let mut walls: Vec<Vec<f64>> = vec![Vec::new(); series.len()];
    let mut loads: Vec<Vec<f64>> = vec![Vec::new(); series.len()];
    let mut events: Vec<Vec<Value>> = vec![Vec::new(); series.len()];
    let cas = work.join("overhead-cas");
    for (s, i) in order {
        let (label, env) = &series[s];
        let wall = match env {
            None => plain_run(&tree, work, &args.step, i)?,
            Some(env) => {
                // Observed: full path, ledger cleared each time so every run
                // misses. The CAS persists, as it would between CI runs.
                let st = work.join(format!("observed-{s}-{i}"));
                let r = run_step(
                    exe,
                    &st,
                    &tree,
                    &args.step,
                    &["--cas", cas.to_str().unwrap()],
                    env,
                )?;
                if r.event["hit"].as_bool() != Some(false)
                    || r.event["exit_code"].as_i64() != Some(0)
                {
                    bail!("observed run {i} was not a passing miss: {}", r.event);
                }
                sp_cas::remove_any(&st)?;
                let wall = r.wall.as_secs_f64();
                eprintln!(
                    "overhead [{label}] {}/{}: {wall:.1}s (execution {:.1}s, load {:.1})",
                    i + 1,
                    args.runs,
                    r.event["exec_ms"].as_f64().unwrap_or(0.0) / 1000.0,
                    loadavg()
                );
                events[s].push(r.event);
                wall
            }
        };
        if env.is_none() {
            eprintln!(
                "overhead [{label}] {}/{}: {wall:.1}s (load {:.1})",
                i + 1,
                args.runs,
                loadavg()
            );
        }
        walls[s].push(wall);
        loads[s].push(loadavg());
    }

    // The first run of each series is warm-up.
    let w: Vec<Vec<f64>> = walls.iter().map(|v| v[1..].to_vec()).collect();
    let exec_median = |s: usize| {
        let v: Vec<f64> = events[s]
            .iter()
            .skip(1)
            .map(|e| e["exec_ms"].as_f64().unwrap_or(0.0) / 1000.0)
            .collect();
        median(&v)
    };
    let (pm, pp) = (median(&w[0]), p95(&w[0]));
    let (om, op) = (median(&w[1]), p95(&w[1]));
    let ratio = om / pm - 1.0;
    let mut t = String::new();
    writeln!(t, "## Overhead (A8)\n")?;
    writeln!(
        t,
        "{} runs per series{}, first dropped as warm-up. Overhead = observed median / plain median - 1. Target under 10%.\n",
        args.runs,
        if args.interleave { ", interleaved" } else { "" }
    )?;
    writeln!(
        t,
        "| Series | Median | p95 | Execution median | Runs (s) | Load average (1m) after each run |\n| --- | --- | --- | --- | --- | --- |"
    )?;
    writeln!(
        t,
        "| {} | {pm:.2}s | {pp:.2}s | {pm:.2}s | {} | {} |",
        series[0].0,
        list(&w[0]),
        list(&loads[0][1..])
    )?;
    for s in 1..series.len() {
        writeln!(
            t,
            "| {} | {:.2}s | {:.2}s | {:.2}s | {} | {} |",
            series[s].0,
            median(&w[s]),
            p95(&w[s]),
            exec_median(s),
            list(&w[s]),
            list(&loads[s][1..])
        )?;
    }
    writeln!(
        t,
        "| **Overhead** | **{:+.1}%** | {:+.1}% | {:+.1}% | | |",
        ratio * 100.0,
        (op / pp - 1.0) * 100.0,
        (exec_median(1) / pm - 1.0) * 100.0
    )?;
    for s in 2..series.len() {
        writeln!(
            t,
            "| Overhead, {} | {:+.1}% | {:+.1}% | {:+.1}% | | |",
            &series[s].0["Observed, ".len()..],
            (median(&w[s]) / pm - 1.0) * 100.0,
            (p95(&w[s]) / pp - 1.0) * 100.0,
            (exec_median(s) / pm - 1.0) * 100.0
        )?;
    }
    writeln!(t)?;
    writeln!(t, "Observed phase breakdown, median over the same runs:\n")?;
    writeln!(
        t,
        "| Phase | Median | Share of observed |\n| --- | --- | --- |"
    )?;
    for (name, field) in [
        ("import", "import_ms"),
        ("lookup", "lookup_ms"),
        ("mount", "mount_ms"),
        ("execution", "exec_ms"),
        ("output diff", "diff_ms"),
        ("ledger write", "record_ms"),
    ] {
        let v: Vec<f64> = events[1]
            .iter()
            .skip(1)
            .map(|s| s[field].as_f64().unwrap_or(0.0) / 1000.0)
            .collect();
        writeln!(
            t,
            "| {name} | {:.2}s | {:.1}% |",
            median(&v),
            median(&v) / om * 100.0
        )?;
    }
    writeln!(t)?;
    let line = format!(
        "Observer overhead (0a, host): median {:+.1}%, p95 {:+.1}% (plain {pm:.2}s, observed {om:.2}s)",
        ratio * 100.0,
        (op / pp - 1.0) * 100.0
    );
    sp_cas::remove_any(&tree)?;
    Ok((t, line))
}

/// One plain run: no FUSE, no overlay; a fresh copy of the tree with an
/// empty GOCACHE, in the same sandbox, uid and env as the observed path. That
/// isolates the observer.
fn plain_run(tree: &Path, work: &Path, step: &str, i: usize) -> anyhow::Result<f64> {
    let copy = work.join(format!("plain-{i}"));
    cp(tree, &copy)?;
    let out = work.join(format!("plain-{i}.log"));
    let rs = sp_sandbox::RunSpec {
        cmd: sp_key::shell_cmd(step),
        cwd: sp_key::WORKSPACE.into(),
        env: sp_key::SPIKE_ENV
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect(),
        mounts: vec![sp_sandbox::Mount {
            src: copy.clone(),
            dst: sp_key::WORKSPACE.into(),
            writable: true,
        }],
        egress: false,
        stdout: out.with_extension("out"),
        stderr: out.with_extension("err"),
        echo: false,
        identity: None,
    };
    let r = sp_sandbox::run(&rs)?;
    if r.exit_code != 0 {
        bail!(
            "plain run {i} exited {}; the baseline must pass",
            r.exit_code
        );
    }
    sp_cas::remove_any(&copy)?;
    Ok(r.wall.as_secs_f64())
}

/// A11: the last N first-parent commits, oldest first, ledger persisting.
fn hit_rate(
    exe: &Path,
    repo: &Path,
    work: &Path,
    args: &BenchArgs,
) -> anyhow::Result<(String, String)> {
    let commits = git(
        repo,
        &[
            "rev-list",
            "--first-parent",
            "-n",
            &args.commits.to_string(),
            "HEAD",
        ],
    )?;
    let mut commits: Vec<String> = commits.lines().map(String::from).collect();
    commits.reverse();
    let tree = work.join("history-tree");
    clone_at(repo, &tree, &commits[0])?;
    copy_module_cache(repo, &tree)?;
    let state = work.join("history-state");
    let mut rows = String::new();
    let (mut hits, mut stillpass_s, mut plain_s) = (0, 0.0, 0.0);
    let mut misses = Vec::new();
    for (i, c) in commits.iter().enumerate() {
        git(&tree, &["checkout", "-q", "--detach", c])?;
        let subject = git(&tree, &["log", "-1", "--format=%s", c])?;
        run_setup(exe, &state, &tree, &args.setup)?;
        let s = run_step(exe, &state, &tree, &args.step, &["--commit", c], &[])?;
        let hit = s.event["hit"].as_bool().unwrap_or(false);
        let wall = s.wall.as_secs_f64();
        // What a plain runner would have spent: the execution itself on a
        // miss, the recorded duration of the matched result on a hit.
        let plain = if hit {
            s.event["recorded_ms"].as_f64().unwrap_or(0.0) / 1000.0
        } else {
            s.event["exec_ms"].as_f64().unwrap_or(0.0) / 1000.0
        };
        stillpass_s += wall;
        plain_s += plain;
        let mismatch = s.event["first_mismatch"].as_str().unwrap_or("").to_string();
        if hit {
            hits += 1;
        } else {
            misses.push((c.clone(), mismatch.clone()));
        }
        writeln!(
            rows,
            "| {} | `{}` | {} | {} | {wall:.1}s | {plain:.1}s | {} |",
            i + 1,
            &c[..10],
            md_cell(&subject, 50),
            if hit { "HIT" } else { "miss" },
            if mismatch.is_empty() {
                "-".to_string()
            } else {
                format!("`{}`", md_cell(&mismatch, 60))
            }
        )?;
        eprintln!(
            "history {}/{} {} {}",
            i + 1,
            commits.len(),
            &c[..10],
            if hit { "HIT" } else { "miss" }
        );
    }
    let saved = (1.0 - stillpass_s / plain_s) * 100.0;
    let mut t = String::new();
    writeln!(t, "## Hit rate (A11)\n")?;
    writeln!(
        t,
        "Last {} first-parent commits, oldest first; step A runs on every commit, step B through the full path with the ledger persisting. Reported, no target. \"Plain runner\" is the observed execution time on a miss (slightly high: it includes observer overhead) and the matched result's recorded duration on a hit.\n",
        commits.len()
    )?;
    writeln!(
        t,
        "| # | Commit | Subject | Step B | Stillpass wall | Plain runner | First mismatch (closest manifest) |\n| --- | --- | --- | --- | --- | --- | --- |"
    )?;
    t += &rows;
    writeln!(
        t,
        "\n**{hits} hits out of {}.** Stillpass {stillpass_s:.0}s vs plain {plain_s:.0}s: {saved:.1}% saved.\n",
        commits.len()
    )?;
    let line = format!(
        "Hit rate (0a): {hits}/{} commits; {stillpass_s:.0}s with Stillpass vs {plain_s:.0}s plain, {saved:.1}% saved",
        commits.len()
    );
    Ok((t, line))
}

/// Miss latency on a one-file change: cold (empty GOCACHE every run) vs warm
/// (--warm, the build cache persisting), interleaved so both series see the
/// same machine. The file changes before every pair, so every run is a miss.
/// The first pair is dropped as warm-up; for the warm series it is also the
/// run that fills the cache.
fn one_file(
    exe: &Path,
    repo: &Path,
    work: &Path,
    args: &BenchArgs,
) -> anyhow::Result<(String, String)> {
    let tree = work.join("onefile-tree");
    clone_at(repo, &tree, "HEAD")?;
    copy_module_cache(repo, &tree)?;
    run_setup(exe, &work.join("onefile-setup-state"), &tree, &args.setup)?;
    let file = tree.join(&args.touch);
    if !file.is_file() {
        bail!("--touch {}: not a file in the tree", args.touch);
    }
    let cold_state = work.join("onefile-cold-state");
    let warm_state = work.join("onefile-warm-state");
    let (mut cold, mut warm) = (Vec::new(), Vec::new());
    for i in 0..args.runs {
        use std::io::Write as _;
        let mut f = std::fs::OpenOptions::new().append(true).open(&file)?;
        writeln!(f, "\n// stillpass bench: one-file change {i}")?;
        drop(f);
        let c = run_step(exe, &cold_state, &tree, &args.step, &[], &[])?;
        let w = run_step(exe, &warm_state, &tree, &args.step, &["--warm"], &[])?;
        for (s, name) in [(&c, "cold"), (&w, "warm")] {
            if s.event["hit"].as_bool() != Some(false) || s.event["exit_code"].as_i64() != Some(0) {
                bail!(
                    "one-file {name} run {i} was not a passing miss: {}",
                    s.event
                );
            }
        }
        eprintln!(
            "one-file {}/{}: cold {:.1}s, warm {:.1}s",
            i + 1,
            args.runs,
            c.wall.as_secs_f64(),
            w.wall.as_secs_f64()
        );
        cold.push(c);
        warm.push(w);
    }
    let walls =
        |v: &[Sample]| -> Vec<f64> { v.iter().skip(1).map(|s| s.wall.as_secs_f64()).collect() };
    let phase = |v: &[Sample], field: &str| -> f64 {
        let xs: Vec<f64> = v
            .iter()
            .skip(1)
            .map(|s| s.event[field].as_f64().unwrap_or(0.0) / 1000.0)
            .collect();
        median(&xs)
    };
    let (cw, ww) = (walls(&cold), walls(&warm));
    let (cm, wm) = (median(&cw), median(&ww));
    let mut t = String::new();
    writeln!(t, "## Miss latency on a one-file change\n")?;
    writeln!(
        t,
        "`{}` gets a comment appended before each pair, so every run is a miss. Cold starts with an empty GOCACHE; warm (`--warm`) starts with the build cache earlier warm runs left behind. {} pairs, first dropped as warm-up (for warm, the run that fills the cache). Interleaved.\n",
        args.touch, args.runs
    )?;
    writeln!(
        t,
        "| Series | Median | p95 | Execution | Output diff | Runs (s) |\n| --- | --- | --- | --- | --- | --- |"
    )?;
    writeln!(
        t,
        "| Cold miss | {cm:.2}s | {:.2}s | {:.2}s | {:.2}s | {} |",
        p95(&cw),
        phase(&cold, "exec_ms"),
        phase(&cold, "diff_ms"),
        list(&cw)
    )?;
    writeln!(
        t,
        "| Warm miss | {wm:.2}s | {:.2}s | {:.2}s | {:.2}s | {} |",
        p95(&ww),
        phase(&warm, "exec_ms"),
        phase(&warm, "diff_ms"),
        list(&ww)
    )?;
    writeln!(t, "| **Warm / cold** | **{:.2}x** | | | | |\n", wm / cm)?;
    let line = format!(
        "One-file miss ({}): cold {cm:.2}s, warm {wm:.2}s ({:.0}% of cold)",
        args.touch,
        wm / cm * 100.0
    );
    sp_cas::remove_any(&tree)?;
    Ok((t, line))
}

fn run_setup(exe: &Path, state: &Path, tree: &Path, step: &str) -> anyhow::Result<()> {
    let st = Command::new(exe)
        .arg("--state")
        .arg(state)
        .args([
            "run",
            "--repo",
            tree.to_str().unwrap(),
            "--allow-net",
            "--step",
            step,
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()?;
    if !st.success() {
        bail!("step A failed in {}", tree.display());
    }
    // Step B starts from a tree whose only earlier output is the module
    // cache: no build cache, no per-day files Go writes under HOME.
    for d in ["gocache", "home"] {
        sp_cas::remove_any(&tree.join(".stillpass").join(d))?;
    }
    Ok(())
}

fn run_step(
    exe: &Path,
    state: &Path,
    tree: &Path,
    step: &str,
    extra: &[&str],
    env: &[(String, String)],
) -> anyhow::Result<Sample> {
    let events = state.join("events.jsonl");
    let before = std::fs::read_to_string(&events)
        .map(|s| s.lines().count())
        .unwrap_or(0);
    let t = Instant::now();
    let out = Command::new(exe)
        .arg("--state")
        .arg(state)
        .args(["run", "--repo", tree.to_str().unwrap(), "--step", step])
        .args(extra)
        .envs(env.iter().map(|(k, v)| (k, v)))
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .output()?;
    let wall = t.elapsed();
    // By banner, not by exit code: a step may exit 2 itself.
    if String::from_utf8_lossy(&out.stderr).contains("STILLPASS  ERROR") {
        bail!(
            "stillpass run failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let text = std::fs::read_to_string(&events)?;
    let line = text
        .lines()
        .skip(before)
        .filter(|l| l.contains("\"message\":\"run\""))
        .last()
        .context("no run event written")?;
    Ok(Sample {
        wall,
        event: serde_json::from_str(line)?,
    })
}

fn clone_at(repo: &Path, dest: &Path, rev: &str) -> anyhow::Result<()> {
    let st = Command::new("git")
        .args(["clone", "-q", "--no-checkout"])
        .arg(repo)
        .arg(dest)
        .status()?;
    if !st.success() {
        bail!("git clone {}", repo.display());
    }
    git(dest, &["checkout", "-q", "--detach", rev])?;
    std::fs::write(dest.join(".git/info/exclude"), ".stillpass/\n")?;
    Ok(())
}

/// Seeds the clone's module cache from the source checkout, so step A only
/// fetches what a commit adds.
fn copy_module_cache(repo: &Path, dest: &Path) -> anyhow::Result<()> {
    let src = repo.join(".stillpass/gomod");
    if src.is_dir() {
        std::fs::create_dir_all(dest.join(".stillpass"))?;
        cp(&src, &dest.join(".stillpass/gomod"))?;
    }
    Ok(())
}

fn cp(src: &Path, dest: &Path) -> anyhow::Result<()> {
    let st = Command::new("cp").arg("-a").arg(src).arg(dest).status()?;
    if !st.success() {
        bail!("cp -a {} {}", src.display(), dest.display());
    }
    Ok(())
}

fn git(dir: &Path, args: &[&str]) -> anyhow::Result<String> {
    let out = Command::new("git").arg("-C").arg(dir).args(args).output()?;
    if !out.status.success() {
        bail!(
            "git {}: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn origin(repo: &Path) -> String {
    git(repo, &["remote", "get-url", "origin"]).unwrap_or_else(|_| repo.display().to_string())
}

fn machine_table(state: &Path) -> anyhow::Result<String> {
    let read = |p: &str| std::fs::read_to_string(p).unwrap_or_default();
    let cpuinfo = read("/proc/cpuinfo");
    let model = cpuinfo
        .lines()
        .find(|l| {
            l.starts_with("model name") || l.starts_with("Model") || l.starts_with("CPU part")
        })
        .and_then(|l| l.split(':').nth(1))
        .map_or("unknown".to_string(), |s| s.trim().to_string());
    let cpus = std::thread::available_parallelism().map_or(0, |n| n.get());
    let mem_kb: u64 = read("/proc/meminfo")
        .lines()
        .find(|l| l.starts_with("MemTotal"))
        .and_then(|l| l.split_whitespace().nth(1))
        .and_then(|n| n.parse().ok())
        .unwrap_or(0);
    let kernel = read("/proc/sys/kernel/osrelease").trim().to_string();
    let arch = std::env::consts::ARCH;
    let disk = Command::new("findmnt")
        .args(["-n", "-o", "FSTYPE,SOURCE", "-T"])
        .arg(state)
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default();
    let mut t = String::new();
    writeln!(t, "## Machine\n")?;
    writeln!(
        t,
        "| CPU | Cores | RAM | Disk (state dir) | Kernel | Arch |\n| --- | --- | --- | --- | --- | --- |"
    )?;
    writeln!(
        t,
        "| {model} | {cpus} | {:.1} GiB | {disk} | {kernel} | {arch} |\n",
        mem_kb as f64 / 1048576.0
    )?;
    Ok(t)
}

/// The one-minute load average, so a run can be told quiet from loaded.
fn loadavg() -> f64 {
    std::fs::read_to_string("/proc/loadavg")
        .ok()
        .and_then(|s| s.split_whitespace().next()?.parse().ok())
        .unwrap_or(f64::NAN)
}

fn median(v: &[f64]) -> f64 {
    percentile(v, 0.5)
}

fn p95(v: &[f64]) -> f64 {
    percentile(v, 0.95)
}

/// Nearest-rank percentile.
fn percentile(v: &[f64], p: f64) -> f64 {
    if v.is_empty() {
        return f64::NAN;
    }
    let mut s = v.to_vec();
    s.sort_by(f64::total_cmp);
    if p == 0.5 && s.len().is_multiple_of(2) {
        return (s[s.len() / 2 - 1] + s[s.len() / 2]) / 2.0;
    }
    let rank = ((p * s.len() as f64).ceil() as usize).clamp(1, s.len());
    s[rank - 1]
}

fn list(v: &[f64]) -> String {
    v.iter()
        .map(|x| format!("{x:.1}"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn md_cell(s: &str, max: usize) -> String {
    let s = s.replace('|', "\\|");
    if s.chars().count() > max {
        format!("{}…", s.chars().take(max).collect::<String>())
    } else {
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn percentiles() {
        let v = [5.0, 1.0, 3.0, 2.0, 4.0];
        assert_eq!(median(&v), 3.0);
        assert_eq!(median(&[1.0, 2.0, 3.0, 10.0]), 2.5);
        assert_eq!(p95(&v), 5.0);
        let many: Vec<f64> = (1..=20).map(f64::from).collect();
        assert_eq!(p95(&many), 19.0);
    }
}
