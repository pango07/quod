//! `stillpass bench`: the two spike numbers, overhead (A8) and hit rate
//! (A11), written to report.md. Every number comes from the run events the
//! child `stillpass run` processes write, never from parsing their output.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context, bail};
use clap::Args;
use serde_json::Value;

use crate::state::State;

#[derive(Args)]
pub struct BenchArgs {
    /// The spike repo checkout. Never modified: the bench works on clones.
    #[arg(long)]
    repo: PathBuf,
    /// Commits for the hit-rate run (A11), oldest first ending at HEAD.
    #[arg(long, default_value_t = 50)]
    commits: usize,
    /// Step B, the memoized step.
    #[arg(long, default_value = "go test ./...")]
    step: String,
    /// Step A, run with network before step B on every commit.
    #[arg(long, default_value = "go mod download")]
    setup: String,
    /// Runs per overhead series; the first of each is dropped as warm-up.
    #[arg(long, default_value_t = 10)]
    runs: usize,
    /// Skip the overhead series (A8).
    #[arg(long)]
    no_overhead: bool,
    /// Skip the hit-rate series (A11).
    #[arg(long)]
    no_hit_rate: bool,
    #[arg(long)]
    vm: bool,
    #[arg(long, default_value = "report.md")]
    out: PathBuf,
}

struct Sample {
    wall: Duration,
    event: Value,
}

pub fn bench(state: &State, args: BenchArgs) -> anyhow::Result<u8> {
    if args.vm {
        bail!("--vm needs the 0b Firecracker backend (T13-T16), which is not built");
    }
    let repo = args.repo.canonicalize()?;
    let work = state.dir.join("bench");
    sp_cas::remove_any(&work)?;
    std::fs::create_dir_all(&work)?;
    let exe = std::env::current_exe()?;
    let head = git(&repo, &["rev-parse", "HEAD"])?;

    let mut report = String::new();
    writeln!(report, "# Stillpass spike benchmark\n")?;
    writeln!(
        report,
        "Spike repo `{}` at `{}`. Step A `{}`, step B `{}`. Generated by `stillpass bench`.\n",
        origin(&repo),
        &head[..12],
        args.setup,
        args.step
    )?;
    report += &machine_table(&state.dir)?;

    let mut totals = Vec::new();
    if !args.no_overhead {
        let (table, line) = overhead(&exe, &repo, &work, &args)?;
        report += &table;
        totals.push(line);
    }
    if !args.no_hit_rate {
        let (table, line) = hit_rate(&exe, &repo, &work, &args)?;
        report += &table;
        totals.push(line);
    }
    writeln!(report, "## Totals\n")?;
    for t in &totals {
        writeln!(report, "- {t}")?;
    }
    std::fs::write(&args.out, &report).with_context(|| format!("write {}", args.out.display()))?;
    eprintln!("wrote {}", args.out.display());
    for t in totals {
        eprintln!("{t}");
    }
    sp_cas::remove_any(&work)?;
    Ok(0)
}

/// A8: plain go test vs the full observed path, both cold.
fn overhead(
    exe: &Path,
    repo: &Path,
    work: &Path,
    args: &BenchArgs,
) -> anyhow::Result<(String, String)> {
    let tree = work.join("overhead-tree");
    clone_at(repo, &tree, "HEAD")?;
    copy_module_cache(repo, &tree)?;
    run_setup(exe, &work.join("setup-state"), &tree, &args.setup)?;

    // Plain: no FUSE, no sandbox; fresh copy of the tree, empty GOCACHE.
    let mut plain = Vec::new();
    for i in 0..args.runs {
        let copy = work.join(format!("plain-{i}"));
        cp(&tree, &copy)?;
        let env = plain_env(&copy);
        let t = Instant::now();
        let st = Command::new("/bin/sh")
            .args(["-e", "-c", &args.step])
            .current_dir(&copy)
            .env_clear()
            .envs(env)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()?;
        plain.push(t.elapsed());
        sp_cas::remove_any(&copy)?;
        eprintln!(
            "overhead plain {}/{}: {:.1}s exit {}",
            i + 1,
            args.runs,
            plain[i].as_secs_f64(),
            st.code().unwrap_or(-1)
        );
    }

    // Observed: full path, ledger cleared each time so every run misses.
    // The CAS persists, as it would between CI runs.
    let mut observed = Vec::new();
    let cas = work.join("overhead-cas");
    for i in 0..args.runs {
        let st = work.join(format!("observed-{i}"));
        let s = run_step(
            exe,
            &st,
            &tree,
            &args.step,
            &["--cas", cas.to_str().unwrap()],
        )?;
        if s.event["hit"].as_bool() != Some(false) {
            bail!("observed run {i} was not a miss");
        }
        eprintln!(
            "overhead observed {}/{}: {:.1}s",
            i + 1,
            args.runs,
            s.wall.as_secs_f64()
        );
        observed.push(s);
        sp_cas::remove_any(&st)?;
    }

    let plain_w: Vec<f64> = plain.iter().skip(1).map(|d| d.as_secs_f64()).collect();
    let obs_w: Vec<f64> = observed
        .iter()
        .skip(1)
        .map(|s| s.wall.as_secs_f64())
        .collect();
    let (pm, pp) = (median(&plain_w), p95(&plain_w));
    let (om, op) = (median(&obs_w), p95(&obs_w));
    let ratio = om / pm - 1.0;
    let mut t = String::new();
    writeln!(t, "## Overhead (A8)\n")?;
    writeln!(
        t,
        "{} runs per series, first dropped as warm-up. Overhead = observed median / plain median - 1. Target under 10%.\n",
        args.runs
    )?;
    writeln!(
        t,
        "| Series | Median | p95 | Runs (s) |\n| --- | --- | --- | --- |"
    )?;
    writeln!(
        t,
        "| Plain (no FUSE, no sandbox) | {pm:.2}s | {pp:.2}s | {} |",
        list(&plain_w)
    )?;
    writeln!(
        t,
        "| Observed (import, serve, overlay, sandbox, record) | {om:.2}s | {op:.2}s | {} |",
        list(&obs_w)
    )?;
    writeln!(
        t,
        "| **Overhead** | **{:+.1}%** | {:+.1}% | |\n",
        ratio * 100.0,
        (op / pp - 1.0) * 100.0
    )?;
    writeln!(t, "Observed phase breakdown, median over the same runs:\n")?;
    writeln!(
        t,
        "| Phase | Median | Share of observed |\n| --- | --- | --- |"
    )?;
    for (name, field) in [
        ("import", "import_ms"),
        ("lookup", "lookup_ms"),
        ("mount", "mount_ms"),
        ("execution", "exec_ms"),
        ("output diff", "diff_ms"),
        ("ledger write", "record_ms"),
    ] {
        let v: Vec<f64> = observed
            .iter()
            .skip(1)
            .map(|s| s.event[field].as_f64().unwrap_or(0.0) / 1000.0)
            .collect();
        writeln!(
            t,
            "| {name} | {:.2}s | {:.1}% |",
            median(&v),
            median(&v) / om * 100.0
        )?;
    }
    writeln!(t)?;
    let line = format!(
        "Observer overhead (0a, host): median {:+.1}%, p95 {:+.1}% (plain {pm:.2}s, observed {om:.2}s)",
        ratio * 100.0,
        (op / pp - 1.0) * 100.0
    );
    sp_cas::remove_any(&tree)?;
    Ok((t, line))
}

/// A11: the last N first-parent commits, oldest first, ledger persisting.
fn hit_rate(
    exe: &Path,
    repo: &Path,
    work: &Path,
    args: &BenchArgs,
) -> anyhow::Result<(String, String)> {
    let commits = git(
        repo,
        &[
            "rev-list",
            "--first-parent",
            "-n",
            &args.commits.to_string(),
            "HEAD",
        ],
    )?;
    let mut commits: Vec<String> = commits.lines().map(String::from).collect();
    commits.reverse();
    let tree = work.join("history-tree");
    clone_at(repo, &tree, &commits[0])?;
    copy_module_cache(repo, &tree)?;
    let state = work.join("history-state");
    let mut rows = String::new();
    let (mut hits, mut stillpass_s, mut plain_s) = (0, 0.0, 0.0);
    let mut misses = Vec::new();
    for (i, c) in commits.iter().enumerate() {
        git(&tree, &["checkout", "-q", "--detach", c])?;
        let subject = git(&tree, &["log", "-1", "--format=%s", c])?;
        run_setup(exe, &state, &tree, &args.setup)?;
        let s = run_step(exe, &state, &tree, &args.step, &["--commit", c])?;
        let hit = s.event["hit"].as_bool().unwrap_or(false);
        let wall = s.wall.as_secs_f64();
        // What a plain runner would have spent: the execution itself on a
        // miss, the recorded duration of the matched result on a hit.
        let plain = if hit {
            s.event["recorded_ms"].as_f64().unwrap_or(0.0) / 1000.0
        } else {
            s.event["exec_ms"].as_f64().unwrap_or(0.0) / 1000.0
        };
        stillpass_s += wall;
        plain_s += plain;
        let mismatch = s.event["first_mismatch"].as_str().unwrap_or("").to_string();
        if hit {
            hits += 1;
        } else {
            misses.push((c.clone(), mismatch.clone()));
        }
        writeln!(
            rows,
            "| {} | `{}` | {} | {} | {wall:.1}s | {plain:.1}s | {} |",
            i + 1,
            &c[..10],
            md_cell(&subject, 50),
            if hit { "HIT" } else { "miss" },
            if mismatch.is_empty() {
                "-".to_string()
            } else {
                format!("`{}`", md_cell(&mismatch, 60))
            }
        )?;
        eprintln!(
            "history {}/{} {} {}",
            i + 1,
            commits.len(),
            &c[..10],
            if hit { "HIT" } else { "miss" }
        );
    }
    let saved = (1.0 - stillpass_s / plain_s) * 100.0;
    let mut t = String::new();
    writeln!(t, "## Hit rate (A11)\n")?;
    writeln!(
        t,
        "Last {} first-parent commits, oldest first; step A runs on every commit, step B through the full path with the ledger persisting. Reported, no target. \"Plain runner\" is the observed execution time on a miss (slightly high: it includes observer overhead) and the matched result's recorded duration on a hit.\n",
        commits.len()
    )?;
    writeln!(
        t,
        "| # | Commit | Subject | Step B | Stillpass wall | Plain runner | First mismatch (closest manifest) |\n| --- | --- | --- | --- | --- | --- | --- |"
    )?;
    t += &rows;
    writeln!(
        t,
        "\n**{hits} hits out of {}.** Stillpass {stillpass_s:.0}s vs plain {plain_s:.0}s: {saved:.1}% saved.\n",
        commits.len()
    )?;
    let line = format!(
        "Hit rate (0a): {hits}/{} commits; {stillpass_s:.0}s with Stillpass vs {plain_s:.0}s plain, {saved:.1}% saved",
        commits.len()
    );
    Ok((t, line))
}

fn run_setup(exe: &Path, state: &Path, tree: &Path, step: &str) -> anyhow::Result<()> {
    let st = Command::new(exe)
        .arg("--state")
        .arg(state)
        .args([
            "run",
            "--repo",
            tree.to_str().unwrap(),
            "--allow-net",
            "--step",
            step,
        ])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()?;
    if !st.success() {
        bail!("step A failed in {}", tree.display());
    }
    Ok(())
}

fn run_step(
    exe: &Path,
    state: &Path,
    tree: &Path,
    step: &str,
    extra: &[&str],
) -> anyhow::Result<Sample> {
    let events = state.join("events.jsonl");
    let before = std::fs::read_to_string(&events)
        .map(|s| s.lines().count())
        .unwrap_or(0);
    let t = Instant::now();
    let out = Command::new(exe)
        .arg("--state")
        .arg(state)
        .args(["run", "--repo", tree.to_str().unwrap(), "--step", step])
        .args(extra)
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .output()?;
    let wall = t.elapsed();
    if out.status.code() == Some(crate::EXIT_STILLPASS_ERROR as i32) {
        bail!(
            "stillpass run failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let text = std::fs::read_to_string(&events)?;
    let line = text
        .lines()
        .skip(before)
        .filter(|l| l.contains("\"message\":\"run\""))
        .last()
        .context("no run event written")?;
    Ok(Sample {
        wall,
        event: serde_json::from_str(line)?,
    })
}

/// The Schemas env with /workspace replaced by the tree's real path, for
/// running without the sandbox's mount namespace.
fn plain_env(tree: &Path) -> Vec<(String, String)> {
    let ws = tree.to_str().unwrap();
    sp_key::SPIKE_ENV
        .iter()
        .map(|(k, v)| (k.to_string(), v.replace(sp_key::WORKSPACE, ws)))
        .collect()
}

fn clone_at(repo: &Path, dest: &Path, rev: &str) -> anyhow::Result<()> {
    let st = Command::new("git")
        .args(["clone", "-q", "--no-checkout"])
        .arg(repo)
        .arg(dest)
        .status()?;
    if !st.success() {
        bail!("git clone {}", repo.display());
    }
    git(dest, &["checkout", "-q", "--detach", rev])?;
    std::fs::write(dest.join(".git/info/exclude"), ".stillpass/\n")?;
    Ok(())
}

/// Seeds the clone's module cache from the source checkout, so step A only
/// fetches what a commit adds.
fn copy_module_cache(repo: &Path, dest: &Path) -> anyhow::Result<()> {
    let src = repo.join(".stillpass/gomod");
    if src.is_dir() {
        std::fs::create_dir_all(dest.join(".stillpass"))?;
        cp(&src, &dest.join(".stillpass/gomod"))?;
    }
    Ok(())
}

fn cp(src: &Path, dest: &Path) -> anyhow::Result<()> {
    let st = Command::new("cp").arg("-a").arg(src).arg(dest).status()?;
    if !st.success() {
        bail!("cp -a {} {}", src.display(), dest.display());
    }
    Ok(())
}

fn git(dir: &Path, args: &[&str]) -> anyhow::Result<String> {
    let out = Command::new("git").arg("-C").arg(dir).args(args).output()?;
    if !out.status.success() {
        bail!(
            "git {}: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn origin(repo: &Path) -> String {
    git(repo, &["remote", "get-url", "origin"]).unwrap_or_else(|_| repo.display().to_string())
}

fn machine_table(state: &Path) -> anyhow::Result<String> {
    let read = |p: &str| std::fs::read_to_string(p).unwrap_or_default();
    let cpuinfo = read("/proc/cpuinfo");
    let model = cpuinfo
        .lines()
        .find(|l| {
            l.starts_with("model name") || l.starts_with("Model") || l.starts_with("CPU part")
        })
        .and_then(|l| l.split(':').nth(1))
        .map_or("unknown".to_string(), |s| s.trim().to_string());
    let cpus = std::thread::available_parallelism().map_or(0, |n| n.get());
    let mem_kb: u64 = read("/proc/meminfo")
        .lines()
        .find(|l| l.starts_with("MemTotal"))
        .and_then(|l| l.split_whitespace().nth(1))
        .and_then(|n| n.parse().ok())
        .unwrap_or(0);
    let kernel = read("/proc/sys/kernel/osrelease").trim().to_string();
    let arch = std::env::consts::ARCH;
    let disk = Command::new("findmnt")
        .args(["-n", "-o", "FSTYPE,SOURCE", "-T"])
        .arg(state)
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default();
    let mut t = String::new();
    writeln!(t, "## Machine\n")?;
    writeln!(
        t,
        "| CPU | Cores | RAM | Disk (state dir) | Kernel | Arch |\n| --- | --- | --- | --- | --- | --- |"
    )?;
    writeln!(
        t,
        "| {model} | {cpus} | {:.1} GiB | {disk} | {kernel} | {arch} |\n",
        mem_kb as f64 / 1048576.0
    )?;
    Ok(t)
}

fn median(v: &[f64]) -> f64 {
    percentile(v, 0.5)
}

fn p95(v: &[f64]) -> f64 {
    percentile(v, 0.95)
}

/// Nearest-rank percentile.
fn percentile(v: &[f64], p: f64) -> f64 {
    if v.is_empty() {
        return f64::NAN;
    }
    let mut s = v.to_vec();
    s.sort_by(f64::total_cmp);
    if p == 0.5 && s.len().is_multiple_of(2) {
        return (s[s.len() / 2 - 1] + s[s.len() / 2]) / 2.0;
    }
    let rank = ((p * s.len() as f64).ceil() as usize).clamp(1, s.len());
    s[rank - 1]
}

fn list(v: &[f64]) -> String {
    v.iter()
        .map(|x| format!("{x:.1}"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn md_cell(s: &str, max: usize) -> String {
    let s = s.replace('|', "\\|");
    if s.chars().count() > max {
        format!("{}…", s.chars().take(max).collect::<String>())
    } else {
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn percentiles() {
        let v = [5.0, 1.0, 3.0, 2.0, 4.0];
        assert_eq!(median(&v), 3.0);
        assert_eq!(median(&[1.0, 2.0, 3.0, 10.0]), 2.5);
        assert_eq!(p95(&v), 5.0);
        let many: Vec<f64> = (1..=20).map(f64::from).collect();
        assert_eq!(p95(&many), 19.0);
    }
}
