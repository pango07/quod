#!/usr/bin/env python3
"""Writes the three benchmark workflows (plain, quod, hosted) into mdemo/workflows/.

They differ only in name, trigger and runs-on; jobs, image, env and steps are
identical, so the comparison is the runner and nothing else.
"""
import pathlib
import sys

# python:3.12-trixie with uv 0.13.6, pinned by digest.
IMAGE = ("ghcr.io/astral-sh/uv:0.13.6-python3.12-trixie"
         "@sha256:101820b96a31d3438aab226230bc5516d62c6b5b506f0e2d72cb4b6975e27dea")
CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1  # v6"

# Upstream's Makefile runs five services with xdist (`-n 4 --dist loadscope`,
# MOTO_CALL_RESET_API=false, clean-slate tests in a separate serial run) and
# every other test directory serially in one pytest. Here each of the five is
# its own job, and the serial directories are split into six alphabetical
# shards of roughly equal duration (globs, so a new service lands in a shard).
PARALLEL = ["batch", "dynamodb", "ec2", "s3", "sqs"]
SHARDS = [("a-b", "[ab]"), ("c", "c"), ("d-e", "[de]"), ("f-m", "[f-m]"), ("n-r", "[n-r]"), ("s-z", "[s-z]")]
XDIST = "./tests/test_(" + "|".join(PARALLEL) + ")"


def workflow(name, on, runs_on, note):
    include = "\n".join(
        [f"          - {{name: {s}, parallel: 'true', paths: ./tests/test_{s}}}" for s in PARALLEL]
        + [f"          - {{name: services {n}, parallel: 'false', paths: './tests/test_{g}*'}}" for n, g in SHARDS])
    return f"""# {note}
# Generated by the Quod benchmark (see QUOD_DEMO.md); plain.yml, quod.yml and
# hosted.yml differ only in name, trigger and runs-on.
name: {name}

on:
{on}

permissions:
  contents: read

jobs:
  test:
    name: ${{{{ matrix.name }}}}
    runs-on: {runs_on}
    timeout-minutes: 30
    container: {IMAGE}
    strategy:
      fail-fast: false
      matrix:
        include:
{include}
    env:
      # Upstream's switch for running without Docker (tests_without_docker.yml).
      TESTS_SKIP_REQUIRES_DOCKER: "true"
    defaults:
      run:
        shell: bash
    steps:
      # A heading for this job's section of the run summary (under Quod, the
      # hooks add one line per step: replayed or executed, and why).
      - name: Summary heading
        run: |
          echo "### moto tests, ${{{{ matrix.name }}}}" >> "$GITHUB_STEP_SUMMARY"

      - uses: {CHECKOUT}

      - name: Install project dependencies
        run: |
          export PIP_CACHE_DIR="$RUNNER_TOOL_CACHE/pip"
          python -m venv .venv
          .venv/bin/pip install -e ".[all,server]" -r requirements-tests.txt

      # pytest collects a directory named on its command line even when
      # --ignore names it, so the five xdist directories are left out here.
      - name: Test with pytest
        if: matrix.parallel == 'false'
        run: |
          dirs=$(ls -d ${{{{ matrix.paths }}}} | grep -v -x -E '{XDIST}')
          .venv/bin/pytest -sv -rs $dirs

      - name: Test with pytest (parallel)
        if: matrix.parallel == 'true'
        run: |
          .venv/bin/pytest -sv -rs ${{{{ matrix.paths }}}} -m requires_clean_slate || test $? -eq 5  # 5: no clean-slate tests here
          MOTO_CALL_RESET_API=false .venv/bin/pytest -sv -n 4 ${{{{ matrix.paths }}}} --dist loadscope -m "not requires_clean_slate"
"""


out = pathlib.Path(__file__).parent / "workflows"
out.mkdir(exist_ok=True)
(out / "plain.yml").write_text(workflow(
    "plain", "  workflow_dispatch:", "[self-hosted, plain]",
    "The official runner, no Quod: dispatched for each commit after quod.yml finishes."))
(out / "quod.yml").write_text(workflow(
    "quod", "  push:\n    branches: [main]", "[self-hosted, quod]",
    "The official runner with Quod's container hooks: runs on every push to main."))
(out / "hosted.yml").write_text(workflow(
    "hosted", "  workflow_dispatch:", "ubuntu-latest",
    "GitHub's hosted runner, for reference: dispatched by hand on a few commits."))
print("ok")
